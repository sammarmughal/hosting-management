// node scripts/phpmyadmin-setup.mjs [--username rehman] [--email billing@abdulrehmaan.net] [--out production-setup.sql]
// node scripts/phpmyadmin-setup.mjs --only <migration name or suffix> [--out file.sql]
//
// For a host without SSH: writes one SQL file that does what `npm run setup:prod`
// does (docs/11 §2), to import into an EMPTY database with phpMyAdmin:
//   1. every migration in prisma/migrations, verbatim and in order,
//   2. the _prisma_migrations table with one finished row per migration
//      (checksum = SHA-256 of migration.sql, as Prisma stores it), so a later
//      `prisma migrate deploy` only applies newer migrations,
//   3. the single admin, with a password nobody knows: sign in with Google
//      (ADMIN_EMAILS), or set a password later with `npm run create-admin -- --force`.
// No settings, templates or demo data: the app uses its built-in defaults.
// The bookkeeping rows come last, so an import that stops halfway records nothing.
//
// --only writes an UPDATE for a database set up earlier (docs/14 §10): just
// that migration plus its _prisma_migrations row, to production-update-<name>.sql.
import { createHash, randomBytes } from "node:crypto"
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"

import { hash } from "@node-rs/argon2"

const ROOT = path.resolve(import.meta.dirname, "..")
const MIGRATIONS = path.join(ROOT, "prisma", "migrations")

function arg(name, fallback) {
  const i = process.argv.indexOf(name)
  return i >= 0 ? process.argv[i + 1] : fallback
}

const migrations = readdirSync(MIGRATIONS, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort()
  .map((name) => {
    const bytes = readFileSync(path.join(MIGRATIONS, name, "migration.sql"))
    if (bytes.includes(Buffer.from("\r\n")))
      throw new Error(
        `${name}/migration.sql has CRLF line endings; check it out with LF.`
      )
    return {
      name,
      sql: bytes.toString("utf8"),
      checksum: createHash("sha256").update(bytes).digest("hex"),
    }
  })

const historyRow = (m) =>
  `  (UUID(), '${m.checksum}', UTC_TIMESTAMP(3), '${m.name}', NULL, NULL, UTC_TIMESTAMP(3), 1)`

const only = arg("--only")
if (only) {
  const m = migrations.find((x) => x.name === only || x.name.endsWith(only))
  if (!m) throw new Error(`No migration matches ${only}`)
  const target = path.resolve(
    arg("--out", path.join(ROOT, `production-update-${m.name}.sql`))
  )
  writeFileSync(
    target,
    `-- Hosting Renewal Manager: database update ${m.name}, for phpMyAdmin.
-- Generated by scripts/phpmyadmin-setup.mjs --only. Import into the LIVE
-- database that already has every earlier migration, after a backup
-- (phpMyAdmin -> Export). Run it once: a second import stops at its first
-- statement and changes nothing. The history row comes last, so an import
-- that stops halfway is not recorded as applied.

SET NAMES utf8mb4;
SET time_zone = '+00:00';

-- ===== Migration ${m.name} =====

${m.sql.trimEnd()}

-- ===== Prisma's migration history =====

INSERT INTO \`_prisma_migrations\`
  (\`id\`, \`checksum\`, \`finished_at\`, \`migration_name\`, \`logs\`, \`rolled_back_at\`, \`started_at\`, \`applied_steps_count\`)
VALUES
${historyRow(m)};
`,
    "utf8"
  )
  console.log(`Wrote ${target}`)
  console.log(`  ${m.name}  ${m.checksum}`)
  process.exit(0)
}

const username = arg("--username", "rehman")
const email = arg("--email", "billing@abdulrehmaan.net").toLowerCase()
const out = path.resolve(arg("--out", path.join(ROOT, "production-setup.sql")))
if (!/^[a-z0-9._-]{3,50}$/i.test(username)) throw new Error(`Bad username: ${username}`)
if (!/^[^\s@']+@[^\s@']+\.[^\s@']+$/.test(email)) throw new Error(`Bad email: ${email}`)

// A valid argon2 hash of 32 random bytes that are thrown away: the password
// form always answers "Invalid credentials." for this admin.
const passwordHash = await hash(randomBytes(32).toString("base64url"))

const parts = [
  `-- Hosting Renewal Manager: production database setup for phpMyAdmin.
-- Generated by scripts/phpmyadmin-setup.mjs from prisma/migrations (${migrations.length} migrations).
-- Import into an EMPTY database (docs/11 §2). It never drops anything: on a
-- database that already has these tables it stops at the first CREATE TABLE.
-- Contains no secrets: the admin's password is random and unknown.

SET NAMES utf8mb4;
SET time_zone = '+00:00';
`,
  ...migrations.map((m) => `-- ===== Migration ${m.name} =====\n\n${m.sql.trimEnd()}\n`),
  `-- ===== Prisma's migration history (as \`prisma migrate deploy\` leaves it) =====

CREATE TABLE \`_prisma_migrations\` (
    \`id\` VARCHAR(36) NOT NULL,
    \`checksum\` VARCHAR(64) NOT NULL,
    \`finished_at\` DATETIME(3) NULL,
    \`migration_name\` VARCHAR(255) NOT NULL,
    \`logs\` TEXT NULL,
    \`rolled_back_at\` DATETIME(3) NULL,
    \`started_at\` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    \`applied_steps_count\` INTEGER UNSIGNED NOT NULL DEFAULT 0,

    PRIMARY KEY (\`id\`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

INSERT INTO \`_prisma_migrations\`
  (\`id\`, \`checksum\`, \`finished_at\`, \`migration_name\`, \`logs\`, \`rolled_back_at\`, \`started_at\`, \`applied_steps_count\`)
VALUES
${migrations.map(historyRow).join(",\n")};
`,
  `-- ===== The single admin (what setup:prod creates) =====

INSERT INTO \`admins\` (\`username\`, \`email\`, \`password_hash\`, \`totp_enabled\`, \`created_at\`, \`updated_at\`)
VALUES ('${username}', '${email}', '${passwordHash}', false, UTC_TIMESTAMP(3), UTC_TIMESTAMP(3));
`,
]

writeFileSync(out, parts.join("\n"), "utf8")
console.log(`Wrote ${out}`)
for (const m of migrations) console.log(`  ${m.name}  ${m.checksum}`)
console.log(`  admin: ${username} <${email}> (no usable password)`)
